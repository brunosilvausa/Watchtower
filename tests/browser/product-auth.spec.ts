import { test, expect } from "@playwright/test";
import { readdir, readFile } from "node:fs/promises";
import { cleanupBrowserFixture } from "./product-fixtures";
import { join } from "node:path";

let fixtureEmail = "";
test.afterEach(async ({}, testInfo) => { if (fixtureEmail) { const cleanup = await cleanupBrowserFixture(fixtureEmail); await testInfo.attach("fixture-cleanup", { body: JSON.stringify(cleanup), contentType: "application/json" }); fixtureEmail = ""; } });
test("real signup, verification, workspace and monitor persist across reload", async ({ page }, testInfo) => {
  test.setTimeout(60000);
  test.skip(!process.env.AUTH_MAIL_DIRECTORY, "Requires explicit local-mail product integration configuration");
  const email = `browser-${testInfo.project.name}-${Date.now()}@example.test`;
  fixtureEmail = email;
  const password = "Local-browser-fixture-42!";
  await page.goto("/signup");
  await page.getByLabel("Nome", { exact: true }).fill("Browser fixture");
  await page.getByLabel("E-mail", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Criar conta", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Conta criada");
  let verification = "";
  await expect.poll(async () => {
    for (const name of await readdir(process.env.AUTH_MAIL_DIRECTORY!)) {
      const mail = JSON.parse(await readFile(join(process.env.AUTH_MAIL_DIRECTORY!, name), "utf8")) as { to: string; url: string };
      if (mail.to === email) { verification = mail.url; return true; }
    }
    return false;
  }).toBe(true);
  await page.goto(verification);
  await page.goto("/login");
  await page.getByLabel("E-mail", { exact: true }).fill(email);
  await page.getByLabel("Senha", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Entrar", exact: true }).click();
  await expect(page).toHaveURL(/dashboard/);
  await page.getByLabel("Nome do workspace").fill("Browser workspace");
  await page.getByRole("button", { name: "Criar workspace", exact: true }).click();
  await expect(page.getByRole("heading", { name: /^Olá,/ })).toBeVisible();
  await page.goto("/dashboard/monitors");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Persisted monitor");
  await page.getByLabel("Destino (URL ou host)").fill("https://example.com");
  await page.getByRole("button", { name: "Salvar monitor" }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Persisted monitor", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("link", { name: "Persisted monitor", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Pausar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Retomar", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole("button", { name: "Retomar", exact: true })).toBeVisible();
  await page.goto("/dashboard/api-keys");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Browser key");
  await page.getByRole("button", { name: "Salvar", exact: true }).click();
  await expect(page.getByText("Copie agora: exibido somente uma vez", { exact: true })).toBeVisible();
  await expect(page.locator("code")).toContainText("wt_live_");
  await page.reload();
  await expect(page.getByText("Copie agora: exibido somente uma vez", { exact: true })).toHaveCount(0);
  await page.goto("/dashboard/status-pages");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Browser status");
  await page.getByLabel("Slug", { exact: true }).fill(`browser-status-${testInfo.project.name}-${Date.now()}`);
  await page.getByLabel("Publicar", { exact: true }).check();
  await page.getByRole("button", { name: "Salvar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("link", { name: "Abrir página", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Browser status", exact: true })).toBeVisible();
  await page.goto("/dashboard/monitors");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Invalid interval");
  await page.getByLabel("Destino (URL ou host)").fill("https://example.com");
  await page.getByLabel("Intervalo em segundos").fill("30");
  await page.getByRole("button", { name: "Salvar monitor" }).click();
  await expect(page.getByRole("dialog").getByRole("alert")).toContainText("Minimum interval");
  await page.getByRole("button", { name: "Cancelar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Adicionar", exact: true })).toBeFocused();
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Protected API workflow");
  await page.getByRole("dialog").getByLabel("Tipo", { exact: true }).selectOption("api");
  await page.getByLabel("Destino (URL ou host)").fill("https://example.com");
  await page.getByLabel("Etapas JSON (máximo 5)").fill('[{"url":"https://example.com/health","method":"GET","expectedStatus":200}]');
  await page.getByRole("button", { name: "Salvar monitor" }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("row").filter({ hasText: "Protected API workflow" }).getByRole("button", { name: "Editar", exact: true }).click();
  await expect(page.getByLabel("Substituir o fluxo protegido")).not.toBeChecked();
  await expect(page.getByLabel("Etapas JSON (máximo 5)")).toHaveCount(0);
  await page.getByLabel("Nome", { exact: true }).fill("Renamed protected workflow");
  const requestPromise = page.waitForRequest(request => request.method() === "PATCH" && request.url().includes("/monitors/"));
  await page.getByRole("button", { name: "Salvar monitor" }).click();
  const editRequest = await requestPromise;
  expect((editRequest.postDataJSON() as { config: Record<string, unknown> }).config).not.toHaveProperty("steps");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("link", { name: "Renamed protected workflow", exact: true })).toBeVisible();
  await page.goto("/dashboard/channels");
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Browser channel");
  await page.getByLabel("Destino", { exact: true }).fill(email);
  await page.getByRole("button", { name: "Salvar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.getByRole("button", { name: "Editar", exact: true }).click();
  await expect(page.getByLabel("Destino", { exact: true })).toHaveValue(email);
  await page.getByLabel("Canal ativo").uncheck();
  await page.getByRole("button", { name: "Salvar", exact: true }).click();
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("button", { name: "Ativar", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Ativar", exact: true }).click();
  await expect(page.getByRole("button", { name: "Desativar", exact: true })).toBeVisible();
  await page.goto("/dashboard/monitors");
  await expect(page.getByRole("link", { name: "Persisted monitor", exact: true })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath("monitor-persisted.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.goto("/dashboard");
  for (const range of ["24h", "7d", "30d"]) {
    await page.getByLabel("Período", { exact: true }).selectOption(range);
    await expect(page.getByLabel("Período", { exact: true })).toHaveValue(range);
    await page.getByLabel("Período", { exact: true }).selectOption(range);
    await expect(page.getByRole("button", { name: "Relatório", exact: true })).toBeEnabled();
  }
  const mobile = testInfo.project.name === "mobile";
  async function openNavigation() { if (mobile) { const menu = page.getByRole("button", { name: "Open navigation", exact: true }); await menu.focus(); await menu.press("Enter"); } }
  await openNavigation();
  await page.getByRole("button", { name: "Novo workspace", exact: true }).click();
  const createDialog = page.getByRole("dialog", { name: "Novo workspace", exact: true });
  await createDialog.getByLabel("Nome do workspace", { exact: true }).fill("Second browser workspace");
  await createDialog.getByRole("button", { name: "Criar workspace", exact: true }).click();
  await expect(createDialog).toHaveCount(0);
  if (!mobile) await expect(page.getByRole("combobox", { name: "Workspace", exact: true })).toHaveValue(/.+/);
  const secondId = await page.getByRole("combobox", { name: "Workspace", exact: true }).inputValue();
  await page.getByRole("link", { name: "Monitores", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Monitores", exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Persisted monitor", exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByRole("heading", { name: "Monitores", exact: true })).toBeVisible();
  await openNavigation();
  await expect(page.getByRole("combobox", { name: "Workspace", exact: true })).toHaveValue(secondId);
  if (mobile) await page.getByRole("dialog", { name: "Navigation", exact: true }).getByRole("button", { name: "Close dialog", exact: true }).click();
  await page.getByRole("button", { name: "Adicionar", exact: true }).click();
  await page.getByLabel("Nome", { exact: true }).fill("Second workspace monitor");
  await page.getByLabel("Destino (URL ou host)").fill("https://example.com");
  const secondRequest = page.waitForRequest(request => request.method() === "POST" && request.url().endsWith("/monitors"));
  await page.getByRole("button", { name: "Salvar monitor" }).click();
  expect((await secondRequest).url()).toContain(`/api/workspaces/${secondId}/monitors`);
  await expect(page.getByRole("dialog")).toHaveCount(0);
  await expect(page.getByRole("link", { name: "Second workspace monitor", exact: true })).toBeVisible();
  await page.goto("/dashboard/settings");
  await page.getByLabel("Idioma", { exact: true }).selectOption("en");
  await page.getByLabel("Fuso horário", { exact: true }).fill("America/New_York");
  await page.getByLabel("Formato de data", { exact: true }).selectOption("YYYY-MM-DD");
  await page.getByRole("button", { name: "Salvar preferências", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Settings", exact: true })).toBeVisible();
  await page.getByLabel("Language", { exact: true }).selectOption("pt");
  await page.getByRole("button", { name: "Save preferences", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Configurações", exact: true })).toBeVisible();
  await openNavigation();
  const signOut = page.getByRole("button", { name: "Sair", exact: true });
  await signOut.focus(); await signOut.press("Enter");
  await expect(page).toHaveURL(/\/login$/);

});
